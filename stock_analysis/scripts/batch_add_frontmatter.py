def find_tags(filename: str) -> list:
    """按文件名关键词匹配分类标签"""
    for keywords, tags in CATEGORY_RULES:
        if any(k in filename for k in keywords):
            return tags
    return ["中华文明", "交易穿透", "其他"]


def file_type(filename: str) -> str:
    """判断笔记类型"""
    if "交易穿透" in filename:
        return "reading-penetration"
    # 早期未标穿透的笔记
    return "book-review"


def has_frontmatter(content: str) -> bool:
    return content.startswith("---")


def build_frontmatter(title: str, date_str: str, tags: list, ftype: str) -> str:
    fm = f"---\ntitle: {title}\ndate: {date_str}\ntags: {json.dumps(tags, ensure_ascii=False)}\ntype: {ftype}\n---\n\n"
    return fm


import json

def process_all():
    files = sorted(NOTES_DIR.glob("*.md"))
    updated = 0
    skipped = 0

    for fpath in files:
        content = fpath.read_text(encoding="utf-8")
        fname = fpath.name

        if has_frontmatter(content):
            print(f"  跳过(已有frontmatter): {fname}")
            skipped += 1
            continue

        # 提取标题: # 后面第一个标题行
        title_match = re.search(r"^#\s+(.+)$", content, re.MULTILINE)
        title = title_match.group(1).strip() if title_match else fname.replace(".md", "")

        # 从文件名提取日期
        date_match = re.match(r"(\d{4}-\d{2}-\d{2})", fname)
        date_str = date_match.group(1) if date_match else "2026-05-24"

        tags = find_tags(fname)
        ftype = file_type(fname)

        fm = build_frontmatter(title, date_str, tags, ftype)
        new_content = fm + content
        fpath.write_text(new_content, encoding="utf-8")
        print(f"  更新: {fname}  tags={tags}")
        updated += 1

    print(f"\n完成: 更新 {updated}, 跳过(已有) {skipped}")


if __name__ == "__main__":
    process_all()
